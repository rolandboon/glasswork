import {
  type EmitScope,
  type Expression,
  emitExpression,
  type LoopVariableName,
  type PathExpression,
  walkExpression,
} from './expression.js';
import type { EachNode, IfNode, OutputNode, TemplateNode } from './template-tree.js';

/**
 * Generates the TypeScript module of a compiled template: the context interface, a render
 * function that builds the HTML in one template literal, and the helpers it uses.
 */

const HEADER = '// This file is auto-generated by @glasswork/email. Do not edit manually.';

const HTML_TO_TEXT_SOURCE = `
/**
 * Converts HTML to plain text for email clients that don't support HTML.
 * Same logic as htmlToText in glasswork/email: skips the head, comments, scripts and
 * hidden preheader text, and keeps link targets.
 */
function htmlToText(html: string): string {
  return html
    .replace(/<head[\\s\\S]*?<\\/head>/gi, '')
    .replace(/<!--[\\s\\S]*?-->/g, '')
    .replace(/<style[^>]*>[\\s\\S]*?<\\/style>/gi, '')
    .replace(/<script[^>]*>[\\s\\S]*?<\\/script>/gi, '')
    .replace(/<(div|span)\\s[^>]*display:\\s*none[^>]*>[\\s\\S]*?<\\/\\1>/gi, '')
    .replace(/<a\\s[^>]*href="([^"]*)"[^>]*>([\\s\\S]*?)<\\/a>/gi, (_match, href, label) => {
      const text = label.replace(/<[^>]+>/g, '').trim();
      if (text) return text === href ? href : text + ': ' + href;
      const alt = /<img\\s[^>]*alt="([^"]*)"/i.exec(label);
      return (alt && alt[1]) || href;
    })
    .replace(/<br\\s*\\/?>/gi, '\\n')
    .replace(/<li(\\s[^>]*)?>/gi, '• ')
    .replace(/<\\/(p|div|li|tr|table|h[1-6])>/gi, '\\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#(\\d+);/g, (match, code) =>
      Number(code) <= 0x10ffff ? String.fromCodePoint(Number(code)) : match
    )
    .replace(/&#x([0-9a-f]+);/gi, (match, code) =>
      Number.parseInt(code, 16) <= 0x10ffff ? String.fromCodePoint(Number.parseInt(code, 16)) : match
    )
    .replace(/&amp;/gi, '&')
    .split('\\n')
    .map((line) => line.replace(/[ \\t]+/g, ' ').trim())
    .join('\\n')
    .replace(/\\n{3,}/g, '\\n\\n')
    .trim();
}
`;

const ESCAPE_HTML_SOURCE = `
/** Escape untrusted values before interpolating them into email HTML. */
function escapeHtml(value: unknown): string {
  return String(value ?? '').replace(/[&<>"']/g, (character) => {
    const entities: Record<string, string> = {
      '&': '&amp;',
      '<': '&lt;',
      '>': '&gt;',
      '"': '&quot;',
      "'": '&#39;',
    };
    return entities[character] ?? character;
  });
}
`;

const SANITIZE_URL_SOURCE = `
/** Restrict dynamic URL attributes to schemes supported by email clients. */
function sanitizeUrl(value: unknown): string {
  const url = String(value ?? '').trim();
  return /^(https?:|mailto:|tel:|cid:|#)/i.test(url) ? escapeHtml(url) : '#';
}
`;

/** Escapes text for a template literal: backslashes, backticks and `${`. */
function escapeTemplateText(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

/** A variable that is the whole value of a quoted href or src attribute. */
function isStandaloneUrlAttribute(html: string, start: number, end: number): boolean {
  const before = html.slice(Math.max(0, start - 64), start);
  const attribute = /\b(?:href|src)\s*=\s*(["'])$/i.exec(before);
  return Boolean(attribute && html.startsWith(attribute[1], end));
}

/** Whether nodes refer to a root name, skipping loops that declare the same name. */
function refersTo(nodes: readonly TemplateNode[], name: string): boolean {
  return nodes.some((node) => nodeRefersTo(node, name));
}

function expressionRefersTo(expression: Expression, name: string): boolean {
  let found = false;
  walkExpression(expression, (node) => {
    if (node.kind === 'path' && node.root === name) found = true;
  });
  return found;
}

function nodeRefersTo(node: TemplateNode, name: string): boolean {
  switch (node.kind) {
    case 'text':
      return false;
    case 'output':
      return expressionRefersTo(node.expression, name);
    case 'if':
      return (
        node.branches.some(
          (branch) => expressionRefersTo(branch.condition, name) || refersTo(branch.body, name)
        ) || refersTo(node.alternate ?? [], name)
      );
    case 'each':
      if (expressionRefersTo(node.array, name)) return true;
      if (node.token.itemName === name || node.token.indexName === name) return false;
      return refersTo(node.body, name);
  }
}

interface Loop {
  itemName: string;
  indexName: string | undefined;
  /** The identifier of the index in the generated code. */
  index: string;
}

interface GenerateModuleOptions {
  interfaceName: string;
  contextInterface: string;
  html: string;
  nodes: readonly TemplateNode[];
}

class RenderEmitter implements EmitScope {
  usesContext = false;
  usesEscapeHtml = false;
  usesSanitizeUrl = false;
  private readonly loops: Loop[] = [];

  constructor(private readonly html: string) {}

  nodes(nodes: readonly TemplateNode[]): string {
    return nodes.map((node) => this.node(node)).join('');
  }

  root(name: string, hasMembers: boolean): string {
    const binding = this.binding(name);
    if (binding?.kind === 'item') return name;
    if (binding?.kind === 'index') {
      if (hasMembers) throw new Error(`Loop index "${name}" is a number and has no properties`);
      return binding.loop.index;
    }
    this.usesContext = true;
    return `ctx.${name}`;
  }

  /** The innermost loop that declares a name as its item or index. */
  private binding(name: string): { kind: 'item' | 'index'; loop: Loop } | undefined {
    for (let index = this.loops.length - 1; index >= 0; index--) {
      const loop = this.loops[index];
      if (loop.itemName === name) return { kind: 'item', loop };
      if (loop.indexName === name) return { kind: 'index', loop };
    }
    return undefined;
  }

  loopVariable(name: LoopVariableName): string {
    const loop = this.loops.at(-1);
    if (!loop) throw new Error(`@${name} can only be used inside an @each block`);
    switch (name) {
      case 'index':
        return loop.index;
      case 'first':
        return `(${loop.index} === 0)`;
      case 'last':
        return `(${loop.index} === __array.length - 1)`;
      case 'length':
        return '__array.length';
    }
  }

  private node(node: TemplateNode): string {
    switch (node.kind) {
      case 'text':
        return escapeTemplateText(node.token.content);
      case 'output':
        return this.output(node);
      case 'if':
        return this.conditional(node);
      case 'each':
        return this.loop(node);
    }
  }

  private expression(expression: Expression, location: string): string {
    try {
      return emitExpression(expression, this);
    } catch (error) {
      throw new Error(`${(error as Error).message}: ${location}`);
    }
  }

  private output(node: OutputNode): string {
    const { expression, token } = node;
    // A bare `{{@first}}` reads as `__index === 0`, without parentheses.
    const code =
      expression.kind === 'loop' && (expression.name === 'first' || expression.name === 'last')
        ? this.expression(expression, token.raw).slice(1, -1)
        : this.expression(expression, token.raw);
    if (token.unescaped) {
      const nullishNeedsParentheses =
        expression.kind === 'conditional' ||
        (expression.kind === 'logical' && expression.operator !== '??');
      return `\${String(${nullishNeedsParentheses ? `(${code})` : code} ?? '')}`;
    }
    this.usesEscapeHtml = true;
    if (isStandaloneUrlAttribute(this.html, token.start, token.end)) {
      this.usesSanitizeUrl = true;
      return `\${sanitizeUrl(${code})}`;
    }
    return `\${escapeHtml(${code})}`;
  }

  private condition(expression: Expression, location: string): string {
    const code = this.expression(expression, location);
    return expression.kind === 'conditional' ? `(${code})` : code;
  }

  private conditional(node: IfNode): string {
    const branches = node.branches.map(
      (branch) =>
        `${this.condition(branch.condition, branch.token.raw)} ? \`${this.nodes(branch.body)}\``
    );
    const alternate = node.alternate ? `\`${this.nodes(node.alternate)}\`` : "''";
    return `\${${branches.join(' : ')} : ${alternate}}`;
  }

  private loop(node: EachNode): string {
    const { itemName, indexName, raw } = node.token;
    const array = this.arrayPath(node.array, raw);
    const usesIndexName = indexName !== undefined && refersTo(node.body, indexName);
    const index = usesIndexName ? indexName : '__index';
    this.loops.push({ itemName, indexName, index });
    const body = this.nodes(node.body);
    this.loops.pop();
    // Unused parameters get reserved names, which noUnusedParameters accepts.
    const item = refersTo(node.body, itemName) ? itemName : '__item';
    return `\${((__array) => __array.map((${item}, ${index}) => \`${body}\`).join(''))(${array})}`;
  }

  private arrayPath(path: PathExpression, location: string): string {
    if (this.binding(path.root)?.kind === 'index') {
      throw new Error(`Cannot loop over the loop index "${path.root}": ${location}`);
    }
    return this.expression(path, location);
  }
}

/** Generates the complete TypeScript module for a compiled template. */
export function generateModule(options: GenerateModuleOptions): string {
  const emitter = new RenderEmitter(options.html);
  const body = emitter.nodes(options.nodes);
  const parameter = emitter.usesContext ? 'ctx' : '_ctx';
  const helpers = [
    HTML_TO_TEXT_SOURCE,
    emitter.usesEscapeHtml ? ESCAPE_HTML_SOURCE : '',
    emitter.usesSanitizeUrl ? SANITIZE_URL_SOURCE : '',
  ].join('');

  return `${HEADER}

${options.contextInterface}

export function render(${parameter}: ${options.interfaceName}): { html: string; text: string } {
  const html = \`${body}\`;

  // Auto-generated plain text version
  const text = htmlToText(html);

  return { html, text };
}
${helpers}`;
}
